"""Static code rating, rebuild-cost valuation and AI-smell estimate for any repo.

Usage:
  python assess.py PATH [PATH ...] [--rate LOW-HIGH] [--json]

PATH      one or more repo folders; several paths are rated together as one system
--rate    monthly cost per engineer in USD, e.g. 5000-7000 (default: three regional bands)
--json    print machine-readable output

Standard library only, Python 3.9+. Reads files, never runs or changes them.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict

SKIP_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "bower_components", "vendor", "third_party",
    "build", "dist", "out", "target", "bin", "obj", ".gradle", ".dart_tool", ".next",
    ".nuxt", ".svelte-kit", "coverage", ".nyc_output", "test-results", "playwright-report",
    "__pycache__", ".venv", "venv", "env", ".tox", ".mypy_cache", ".pytest_cache",
    "Pods", "DerivedData", ".idea", ".vscode", "logs", "tmp", "migrations_generated",
}

LANGUAGES = {
    ".java": "Java", ".kt": "Kotlin", ".kts": "Kotlin", ".scala": "Scala", ".groovy": "Groovy",
    ".py": "Python", ".rb": "Ruby", ".php": "PHP", ".go": "Go", ".rs": "Rust",
    ".c": "C", ".h": "C", ".cc": "C++", ".cpp": "C++", ".hpp": "C++", ".cs": "C#",
    ".swift": "Swift", ".m": "Objective-C", ".dart": "Dart",
    ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript", ".cjs": "JavaScript",
    ".ts": "TypeScript", ".tsx": "TypeScript", ".vue": "Vue", ".svelte": "Svelte",
    ".sql": "SQL", ".sh": "Shell", ".ps1": "PowerShell", ".lua": "Lua", ".ex": "Elixir",
    ".exs": "Elixir", ".erl": "Erlang", ".hs": "Haskell", ".clj": "Clojure", ".r": "R",
    ".cbl": "COBOL", ".cob": "COBOL",
}

GENERATED_NAME = re.compile(
    r"(\.g|\.freezed|\.gr|\.config|\.mocks|\.pb|_pb2|\.generated|\.designer)\.\w+$"
    r"|\.min\.(js|css)$|app_localizations|R\.java$|BuildConfig\.java$|-lock\.|\.lock$",
    re.I)
GENERATED_HEADER = re.compile(r"generated by|do not edit|auto-?generated|@generated", re.I)

# Third-party code copied into the repo: library banners, minified bundles, asset vendor folders.
WEB_ASSETS = (".js", ".jsx", ".mjs", ".cjs")
VENDOR_HEADER = re.compile(
    r"@license|/\*!|\(c\)\s*\d{4}.*\b(MIT|BSD|Apache)\b|Licensed under the|jQuery|Bootstrap v\d", re.I)
VENDOR_PATH = re.compile(
    r"(^|/)(assets|static|public|web-app|wwwroot|resources|www)/(.*/)?"
    r"(js|vendor|vendors|plugins|libs?|third[-_]?party)/", re.I)

TEST_PATH = re.compile(
    r"(^|/)(tests?|__tests__|spec|specs|integration_test|e2e|src/test|androidTest)(/|$)"
    r"|[._-](test|spec)s?\.\w+$|(^|/)test_[^/]+\.py$|_test\.(go|py|dart|rb|exs)$"
    r"|(Test|Tests|IT|Spec)\.(java|kt|scala|groovy|cs|swift)$", re.I)

TEST_CASE = re.compile(
    r"@(Test|ParameterizedTest|RepeatedTest|TestFactory)\b"
    r"|^\s*(it|test|testWidgets|blocTest|specify)(\.each\b[^(]*)?\s*\("
    r"|^\s*(async\s+)?def\s+test_\w+"
    r"|^\s*func\s+Test\w+\s*\("
    r"|^\s*\[(Fact|Theory|Test|TestMethod)\b"
    r"|#\[test\]",
    re.M)

COMMENT_LINE = re.compile(r"^\s*(//|#(?!include|define|if|endif|pragma|!)|\*|/\*|<!--|--\s)")
COMMENTED_CODE = re.compile(
    r"^\s*(//|#)\s*(return\b|if\s*\(|for\s*\(|while\s*\(|\}|\w+\s*=\s*[^=]|\w+\([^)]*\);\s*$"
    r"|import\s|public\s|private\s|const\s|let\s|var\s|def\s|class\s)")

HIDDEN = re.compile("[\u200B-\u200F\u202A-\u202E\u2060-\u2064\u2066-\u2069\uFEFF\u00AD\u180E]")
SCRIPT_TEXT = re.compile("[\u0590-\u08FF\u0900-\u0DFF\u0E00-\u0FFF\u1100-\u11FF\uAC00-\uD7AF]")
EMOJI = re.compile("[\U0001F300-\U0001FAFF\u2600-\u27BF\u2B50\u2B55]")

SMELLS = {
    # name: (pattern, applies to comments only)
    "empty_catch": (re.compile(
        r"catch\s*(\([^)]*\))?\s*\{\s*\}|\.catch\(\s*\(\s*\w*\s*\)\s*=>\s*(undefined|null|\{\s*\})\s*\)"
        r"|except[^:\n]*:\s*(pass|\.\.\.)\s*$|rescue\s*(=>\s*\w+)?\s*;?\s*end|catch\s*\(_\)\s*\{\s*\}",
        re.M), False),
    "catch_all": (re.compile(
        r"catch\s*\(\s*(final\s+)?(Exception|Throwable|RuntimeException)\s+\w+\s*\)"
        r"|catch\s*\(\s*(Exception|SystemException)\s*(\w+)?\s*\)"
        r"|except\s*(Exception|BaseException)?\s*(as\s+\w+)?\s*:|rescue\s*(=>|$)",
        re.M), False),
    "debug_output": (re.compile(
        r"console\.(log|debug)\(|System\.(out|err)\.print|(?<![\w.])print\(|printStackTrace\(\)"
        r"|fmt\.Print|var_dump\(|(?<![\w.>])dd\(|debugPrint\("), False),
    "untyped": (re.compile(r":\s*any\b|\bas\s+any\b|<any>|@SuppressWarnings\(\"(unchecked|rawtypes)\"\)"
                           r"|#\s*type:\s*ignore|//\s*@ts-ignore|eslint-disable"), False),
    "todo": (re.compile(r"\b(TODO|FIXME|HACK|XXX)\b"), True),
    "narrating_comment": (re.compile(
        r"\b(fixed|added|updated|changed|refactored|now uses|new:|was:|previously|"
        r"as requested|per (your|the) request|step \d+[:.]|here we|let's|let us|we now)\b", re.I), True),
    "ai_vocabulary": (re.compile(
        r"\b(delve|seamless(ly)?|robust|comprehensive|leverag(e|es|ing)|utiliz(e|es|ing)|"
        r"streamline[sd]?|elegant(ly)?|cutting-edge|meticulous(ly)?|holistic|"
        r"it'?s (important|worth) (to note|noting)|ensure that|this (function|method|class) "
        r"(is responsible for|handles|will)|enhanced?|best practices?)\b", re.I), True),
    "tool_mention": (re.compile(
        r"\b(claude|anthropic|chatgpt|gpt-?[345]|openai|copilot|gemini|llm|ai[- ]generated|"
        r"generated (by|with) (ai|an? (llm|assistant)))\b", re.I), True),
    "banner_comment": (re.compile(r"^\s*(//|#|/\*+|\*)\s*([=\-*#~]{8,})", re.M), False),
}

# Dart: `catch (e)` with no `on Type` in front catches everything.
DART_CATCH_ALL = re.compile(r"\}\s*catch\s*\(\s*\w+(\s*,\s*\w+)?\s*\)\s*\{")
# Command-line tools print by design.
TOOL_PATH = re.compile(r"(^|/)(scripts?|tools?|bin|cli|cmd)/", re.I)

SECRET_PATTERNS = {
    "aws_key": re.compile(r"AKIA[0-9A-Z]{16}"),
    "google_key": re.compile(r"AIza[0-9A-Za-z_\-]{35}"),
    "private_key": re.compile(r"-----BEGIN (RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----"),
    "slack_token": re.compile(r"xox[baprs]-[0-9A-Za-z-]{10,}"),
    "github_token": re.compile(r"gh[pousr]_[0-9A-Za-z]{36}"),
    "hardcoded_password": re.compile(
        r"(password|passwd|pwd|secret|api[_-]?key)\s*[:=]\s*['\"][^'\"\s$%{}<>]{6,}['\"]", re.I),
}
# Firebase client keys ship inside every app build and are public by design: restrict, don't hide.
PUBLIC_CLIENT_CONFIG = re.compile(r"(google-services\.json|GoogleService-Info\.plist)$", re.I)
HIGH_RISK = {"aws_key", "private_key", "slack_token", "github_token", "hardcoded_password"}
SECRET_FILES = re.compile(r"(^|/)\.env(\.[\w-]+)?$|\.(ya?ml|properties|json|xml|plist|gradle|toml|ini|cfg)$|"
                          r"(^|/)(AndroidManifest\.xml|AppDelegate\.swift)$", re.I)
SECRET_EXEMPT = re.compile(r"example|sample|template|test|spec|mock|fixture|dummy", re.I)

AI_TRAILER = re.compile(r"co-authored-by:.*(claude|anthropic|copilot|openai|gpt)|generated with \[?(claude|chatgpt)",
                        re.I)

# Weights and the density (hits per 1,000 app lines) at which a signal is fully "smelly".
AI_SIGNALS = {
    "tool_mention": (20, 0.05),
    "ai_vocabulary": (15, 1.0),
    "narrating_comment": (15, 2.0),
    "banner_comment": (5, 2.0),
    "comment_density": (10, None),
    "emoji": (10, 0.2),
    "hidden_chars": (10, 0.05),
    "catch_all": (5, 6.0),
    "empty_catch": (5, 2.0),
    "duplication": (5, None),
}

DEFAULT_RATES = {
    "South Asia": (2_000, 3_000),
    "Eastern Europe / LatAm": (5_000, 7_000),
    "US / Western Europe": (12_000, 15_000),
}


def iter_files(root):
    for directory, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
        for name in files:
            yield os.path.join(directory, name)


def read_text(path):
    try:
        with open(path, "rb") as handle:
            raw = handle.read(2_000_000)
    except OSError:
        return None
    if b"\0" in raw[:4096]:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return raw.decode("latin-1")


def hidden_count(text):
    """Invisible characters inside the text. A byte-order mark at offset 0 is an editor habit, not counted."""
    hits = 0
    for match in HIDDEN.finditer(text):
        i = match.start()
        cp = ord(match.group())
        if cp == 0xFEFF and i == 0:
            continue
        near_script = SCRIPT_TEXT.match(text[i - 1:i] or " ") or SCRIPT_TEXT.match(text[i + 1:i + 2] or " ")
        if cp in (0x200C, 0x200D, 0x200E, 0x200F) and near_script:
            continue
        hits += 1
    return hits


def comment_text(lines):
    return "\n".join(line for line in lines if COMMENT_LINE.match(line))


def scan(paths):
    stats = Counter()
    smells = Counter()
    languages = Counter()
    secrets = []
    big_files = []
    hidden_files = []
    windows = defaultdict(int)
    window_size = 6

    for root in paths:
        for path in iter_files(root):
            rel = os.path.relpath(path, root).replace("\\", "/")
            name = os.path.basename(path)
            ext = os.path.splitext(name)[1].lower()

            if SECRET_FILES.search(rel) and not SECRET_EXEMPT.search(rel):
                text = read_text(path)
                if text:
                    for kind, pattern in SECRET_PATTERNS.items():
                        for _ in pattern.finditer(text):
                            if kind == "google_key" and PUBLIC_CLIENT_CONFIG.search(rel):
                                kind = "firebase_client_key"
                            secrets.append((f"{os.path.basename(root)}/{rel}", kind))

            if ext not in LANGUAGES or GENERATED_NAME.search(name):
                continue
            text = read_text(path)
            if text is None or GENERATED_HEADER.search(text[:400]):
                continue
            if ext in WEB_ASSETS and (VENDOR_PATH.search(rel) or VENDOR_HEADER.search(text[:600])):
                stats["vendor_lines_skipped"] += text.count("\n")
                continue

            lines = [line for line in text.splitlines() if line.strip()]
            if not lines:
                continue
            if sum(len(line) for line in lines) / len(lines) > 250:
                stats["vendor_lines_skipped"] += len(lines)
                continue
            is_test = bool(TEST_PATH.search(rel))
            languages[LANGUAGES[ext]] += len(lines)

            if text.startswith(chr(0xFEFF)):
                stats["bom_files"] += 1
            hidden = hidden_count(text)
            if hidden:
                hidden_files.append(f"{os.path.basename(root)}/{rel}")
                smells["hidden_chars"] += hidden

            if is_test:
                stats["test_lines"] += len(lines)
                stats["test_cases"] += len(TEST_CASE.findall(text))
                continue

            stats["app_lines"] += len(lines)
            stats["app_files"] += 1
            if len(lines) > 600:
                big_files.append((f"{os.path.basename(root)}/{rel}", len(lines)))

            comments = comment_text(lines)
            stats["comment_lines"] += sum(1 for line in lines if COMMENT_LINE.match(line))
            stats["commented_code"] += sum(1 for line in lines if COMMENTED_CODE.match(line))
            is_tool = bool(TOOL_PATH.search(rel))
            for key, (pattern, comments_only) in SMELLS.items():
                if key == "debug_output" and is_tool:
                    continue
                smells[key] += len(pattern.findall(comments if comments_only else text))
            if ext == ".dart":
                smells["catch_all"] += len(DART_CATCH_ALL.findall(text))
            smells["emoji"] += len(EMOJI.findall(text))

            normalized = [re.sub(r"\s+", " ", line.strip()) for line in lines]
            normalized = [line for line in normalized if len(line) > 12 and not COMMENT_LINE.match(line)]
            for i in range(len(normalized) - window_size + 1):
                digest = hashlib.md5("\n".join(normalized[i:i + window_size]).encode()).digest()
                windows[digest] += 1

    repeated = sum(count - 1 for count in windows.values() if count > 1)
    stats["duplicated_windows"] = repeated
    stats["windows"] = max(1, sum(windows.values()))
    return stats, smells, languages, secrets, big_files, hidden_files


def git_facts(paths):
    commits = authors = trailers = 0
    for root in paths:
        try:
            log = subprocess.run(["git", "-C", root, "log", "--all", "--format=%ae%x1f%B%x1e"],
                                 capture_output=True, text=True, encoding="utf-8", errors="replace",
                                 timeout=60).stdout
        except (OSError, subprocess.TimeoutExpired):
            continue
        entries = [e for e in log.split("\x1e") if e.strip()]
        commits += len(entries)
        authors += len({e.split("\x1f", 1)[0].strip() for e in entries})
        trailers += sum(1 for e in entries if AI_TRAILER.search(e))
    return {"commits": commits, "authors": authors, "ai_trailers": trailers}


def per_kloc(count, app_lines):
    return count / max(app_lines / 1000, 0.001)


def clamp(value, low=0.0, high=10.0):
    return max(low, min(high, value))


def ai_smell(stats, smells, git):
    app = stats["app_lines"]
    comment_ratio = stats["comment_lines"] / max(app, 1)
    duplication = stats["duplicated_windows"] / stats["windows"]
    parts = {}
    for key, (weight, full_at) in AI_SIGNALS.items():
        if key == "comment_density":
            # human code typically sits at 5-20% comment lines; generated code often runs well above
            level = clamp((comment_ratio - 0.22) / 0.18, 0, 1)
        elif key == "duplication":
            level = clamp((duplication - 0.04) / 0.11, 0, 1)
        else:
            level = clamp(per_kloc(smells[key], app) / full_at, 0, 1)
        parts[key] = round(level * weight, 2)
    total_weight = sum(weight for weight, _ in AI_SIGNALS.values())
    score = sum(parts.values()) / total_weight * 100
    if git["ai_trailers"]:
        score = max(score, 5.0)
    return round(score, 1), parts


def rating(stats, smells, secrets, big_files):
    app = max(stats["app_lines"], 1)
    test_ratio = stats["test_lines"] / app
    duplication = stats["duplicated_windows"] / stats["windows"]
    cases_per_kloc = per_kloc(stats["test_cases"], app)

    tests = clamp(10 * min(test_ratio / 0.6, 1) * 0.6 + 10 * min(cases_per_kloc / 15, 1) * 0.4)
    maintainability = clamp(
        10
        - 30 * max(duplication - 0.03, 0)
        - 2.5 * min(len(big_files) / max(stats["app_files"], 1) / 0.05, 1)
        - 1.5 * min(per_kloc(stats["commented_code"], app) / 10, 1)
        - 1.0 * min(per_kloc(smells["todo"], app) / 3, 1))
    robustness = clamp(
        10
        - 3.0 * min(per_kloc(smells["empty_catch"], app) / 0.5, 1)
        - 3.0 * min(per_kloc(smells["catch_all"], app) / 3, 1)
        - 2.0 * min(per_kloc(smells["untyped"], app) / 3, 1)
        - 2.0 * min(per_kloc(smells["debug_output"], app) / 2, 1))
    high = [s for s in secrets if s[1] in HIGH_RISK]
    low = [s for s in secrets if s[1] not in HIGH_RISK]
    security = clamp(10 - 2.5 * len({kind for _, kind in high}) - 0.5 * min(len(high), 6)
                     - 0.25 * min(len(low), 4) - 1.0 * min(smells["hidden_chars"], 1))
    parts = {"tests": tests, "maintainability": maintainability, "robustness": robustness,
             "security_hygiene": security}
    weights = {"tests": 0.3, "maintainability": 0.25, "robustness": 0.25, "security_hygiene": 0.2}
    overall = sum(parts[k] * weights[k] for k in parts)
    return round(overall, 1), {k: round(v, 1) for k, v in parts.items()}


def valuation(app_lines, rates):
    kloc = app_lines / 1000
    cocomo = 2.4 * kloc ** 1.05
    # Basic COCOMO reflects 1980s productivity; modern frameworks cut effort sharply.
    low, high = max(1, round(cocomo * 0.18)), max(1, round(cocomo * 0.26))
    return {
        "kloc": round(kloc, 1),
        "cocomo_person_months": round(cocomo),
        "person_months": [low, high],
        "cost_usd": {region: [low * a, high * b] for region, (a, b) in rates.items()},
    }


def parse_args(argv):
    paths, rates, as_json = [], DEFAULT_RATES, False
    args = iter(argv)
    for arg in args:
        if arg == "--json":
            as_json = True
        elif arg == "--rate":
            low, _, high = next(args, "").partition("-")
            if not (low.isdigit() and high.isdigit()):
                sys.exit("--rate expects LOW-HIGH, e.g. 5000-7000")
            rates = {"Custom": (int(low), int(high))}
        elif arg in ("-h", "--help"):
            sys.exit(__doc__)
        else:
            paths.append(os.path.abspath(arg))
    if not paths:
        sys.exit(__doc__)
    for path in paths:
        if not os.path.isdir(path):
            sys.exit(f"not a folder: {path}")
    return paths, rates, as_json


def main():
    paths, rates, as_json = parse_args(sys.argv[1:])
    stats, smells, languages, secrets, big_files, hidden_files = scan(paths)
    if not stats["app_lines"]:
        sys.exit("no source files found")
    git = git_facts(paths)
    overall, parts = rating(stats, smells, secrets, big_files)
    smell_score, smell_parts = ai_smell(stats, smells, git)
    value = valuation(stats["app_lines"], rates)
    app = stats["app_lines"]

    report = {
        "paths": paths,
        "size": {
            "app_lines": app, "test_lines": stats["test_lines"], "test_cases": stats["test_cases"],
            "files": stats["app_files"], "languages": dict(languages.most_common()),
            "comment_ratio": round(stats["comment_lines"] / app, 3),
            "duplication_ratio": round(stats["duplicated_windows"] / stats["windows"], 3),
        },
        "rating": {"overall": overall, **parts},
        "ai_smell": {"score_percent": smell_score, "contributions": smell_parts},
        "signals_per_kloc": {k: round(per_kloc(v, app), 2) for k, v in sorted(smells.items())},
        "signals_total": dict(sorted(smells.items())),
        "secrets": [{"file": f, "kind": k} for f, k in secrets],
        "large_files": [{"file": f, "lines": n} for f, n in sorted(big_files, key=lambda x: -x[1])[:10]],
        "hidden_char_files": hidden_files[:20],
        "git": git,
        "valuation": value,
    }

    if as_json:
        print(json.dumps(report, indent=2))
        return

    size = report["size"]
    print("SIZE")
    print(f"  app lines      {app:>10,}   in {size['files']:,} files")
    print(f"  test lines     {stats['test_lines']:>10,}   test cases {stats['test_cases']:,}")
    print(f"  languages      " + ", ".join(f"{k} {v:,}" for k, v in list(languages.most_common())[:6]))
    print(f"  comments       {size['comment_ratio']:.1%} of app lines")
    print(f"  duplication    {size['duplication_ratio']:.1%} of 6-line windows repeat")
    if stats["bom_files"]:
        print(f"  byte-order mark {stats['bom_files']:,} files (editor artefact, not scored)")
    if stats["vendor_lines_skipped"]:
        print(f"  skipped        {stats['vendor_lines_skipped']:,} lines of vendored or minified code")
    if git["commits"]:
        print(f"  git            {git['commits']:,} commits, {git['authors']} authors")

    print("\nCODE RATING (0-10, static heuristics)")
    print(f"  overall          {overall:>4}")
    for key, value_ in parts.items():
        print(f"  {key:<16} {value_:>4}")

    print("\nAI-SMELL ESTIMATE")
    print(f"  score            {smell_score}%   (under 5% reads as human-written)")
    for key, points in sorted(smell_parts.items(), key=lambda x: -x[1]):
        if points:
            print(f"    {key:<20} +{points}")
    if git["ai_trailers"]:
        print(f"    AI commit trailers   {git['ai_trailers']}")

    print("\nSIGNALS (total / per 1k app lines)")
    for key in sorted(smells):
        print(f"  {key:<20} {smells[key]:>6} {per_kloc(smells[key], app):>8.2f}")
    print(f"  {'commented_code':<20} {stats['commented_code']:>6} {per_kloc(stats['commented_code'], app):>8.2f}")

    if secrets:
        print("\nPOSSIBLE SECRETS (check by hand)")
        for f, kind in sorted(set(secrets), key=lambda s: (s[1] not in HIGH_RISK, s[0]))[:15]:
            level = "HIGH" if kind in HIGH_RISK else "low "
            print(f"  {level}  {kind:<20} {f}")
    if big_files:
        print("\nLARGEST FILES (> 600 lines)")
        for f, n in report["large_files"][:5]:
            print(f"  {n:>6}  {f}")
    if hidden_files:
        print("\nHIDDEN CHARACTERS IN")
        for f in hidden_files[:10]:
            print(f"  {f}")

    print(f"\nVALUATION (cost to rebuild, {value['kloc']} KLOC)")
    print(f"  basic COCOMO     {value['cocomo_person_months']} person-months (upper bound)")
    low, high = value["person_months"]
    print(f"  realistic        {low}-{high} person-months")
    for region, (a, b) in value["cost_usd"].items():
        print(f"  {region:<24} ${a:>11,} - ${b:>11,}")


if __name__ == "__main__":
    main()
